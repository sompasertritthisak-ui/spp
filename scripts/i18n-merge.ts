/**
 * Merges translated batches (scripts/data/lao/*.txt, see below) into
 * src/content/lao/segments.json after checking each one:
 * same tags, same number slots, Lao script present. A bad entry is reported
 * and left out; nothing partial reaches the site.
 *
 *   npx tsx scripts/i18n-merge.ts
 */
import { mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { validateTranslation } from "../src/lib/i18n/segments";

const ROOT = join(__dirname, "..");
const target = join(ROOT, "src/content/lao/segments.json");
const data = JSON.parse(readFileSync(target, "utf8")) as { segments: Record<string, string>; attrs: Record<string, string> };
const known = JSON.parse(readFileSync(join(ROOT, "scripts/data/i18n-segments.json"), "utf8")) as { segments: Record<string, string[]>; attrs: Record<string, string[]> };
let added = 0, bad = 0;
/*
 * A batch is scripts/data/lao/<name>.txt: one line per translation, "N<TAB>Lao",
 * where N is the 1-based position of the key in scripts/data/pending/<name>.json
 * (so long keys are never retyped). A merged batch moves to lao/done/.
 */
const dir = join(ROOT, "scripts/data/lao");
mkdirSync(join(dir, "done"), { recursive: true });
for (const f of readdirSync(dir).filter((f) => f.endsWith(".txt")).sort()) {
  const name = f.replace(/\.txt$/, "");
  const pending = JSON.parse(readFileSync(join(ROOT, `scripts/data/pending/${name}.json`), "utf8")) as Record<string, string>;
  const keys = Object.keys(pending);
  const isAttr = name.startsWith("attrs");
  let ok = true;
  for (const line of readFileSync(join(dir, f), "utf8").split("\n")) {
    const m = /^(\d+)\t(.+)$/.exec(line.trim() ? line : "");
    if (!m) continue;
    const key = keys[Number(m[1]) - 1], lo = m[2]!.trim();
    if (!key) { bad++; ok = false; console.error(`✗ ${f}: no key ${m[1]}`); continue; }
    const problem = validateTranslation(key, lo);
    if (problem) { bad++; ok = false; console.error(`✗ ${f} #${m[1]}: ${problem}\n    ${key}\n    ${lo}`); continue; }
    const into = isAttr ? data.attrs : data.segments;
    if (into[key] !== lo) added++;
    into[key] = lo;
  }
  // every processed batch retires, whole or not: the pending files are regenerated by each extraction, so a
  // batch left behind would be re-read against a different key order next time (rejected lines are kept for review)
  renameSync(join(dir, f), join(dir, "done", f));
  if (!ok) console.error(`  ${f}: the rejected lines above were not merged; fix them in a fresh batch against the current pending file`);
}
// drop entries whose key no longer exists on the site
for (const k of Object.keys(data.segments)) if (!(k in known.segments)) delete data.segments[k];
for (const k of Object.keys(data.attrs)) if (!(k in known.attrs)) delete data.attrs[k];
const sortObj = (o: Record<string, string>) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(target, JSON.stringify({ segments: sortObj(data.segments), attrs: sortObj(data.attrs) }, null, 1) + "\n");
console.log(`${added} translations added or changed, ${bad} rejected · ${Object.keys(data.segments).length} segments and ${Object.keys(data.attrs).length} attributes translated of ${Object.keys(known.segments).length} / ${Object.keys(known.attrs).length}`);
process.exit(bad ? 1 : 0);
